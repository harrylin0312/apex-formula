import assert from 'node:assert/strict';
import {Scene} from '../dist/vendor/three.module.js';
import {tyreSmokeIntensity,createTyreSmoke} from '../dist/tyre-smoke.js';
import {createCar,setVelocity,drive} from '../dist/core.js';
const car={a:0,vx:0,vz:20,yaw:0};
const rolling={fz:2000,utilization:1,x:0,l:0,steer:0,omega:20/.36};
assert.equal(tyreSmokeIntensity(car,rolling),0,'saturated rolling tyre must not smoke');
assert(tyreSmokeIntensity(car,{...rolling,omega:0})>.9,'locked tyre must smoke');
assert(tyreSmokeIntensity({...car,vz:0},{...rolling,omega:60})>.9,'stationary burnout must smoke');
assert.equal(tyreSmokeIntensity(car,{...rolling,omega:0,fz:0}),0,'unloaded wheel must not smoke');
assert.equal(tyreSmokeIntensity(car,{...rolling,omega:0,utilization:.8}),0,'unsaturated tyre must not smoke');
assert(tyreSmokeIntensity({...car,vx:8},rolling)>.9,'lateral sliding must smoke');
const real=createCar(100);setVelocity(real,25);for(let i=0;i<60;i++)drive(real,{brake:1},1/120,false);
assert(real.wheels.some(w=>tyreSmokeIntensity(real,w)>0),'real braking saturation triggers smoke');
globalThis.document={createElement:()=>({getContext:()=>({createRadialGradient:()=>({addColorStop(){}}),fillRect(){}})})};
const scene=new Scene(),smoke=createTyreSmoke(scene,{capacity:4,random:()=>.5});
const wheels=[{...rolling,id:'FL',x:-.9,omega:0},{...rolling,id:'FR',x:.9}];
const source={...car,x:10,z:20,wheels};
smoke.update(.05,[source]);assert(smoke.activeCount>0);
const sprites=scene.getObjectByName('tyre-smoke').children.filter(s=>s.visible);
assert(sprites.every(s=>s.position.x===9.1),'only slipping left wheel emits at its contact point');
for(let i=0;i<20;i++)smoke.update(.05,[source]);assert(smoke.activeCount<=4,'pool stays bounded');
smoke.update(2,[],false);assert.equal(smoke.activeCount,0,'smoke expires');
smoke.update(.05,[source]);smoke.clear();assert.equal(smoke.activeCount,0);
smoke.dispose();assert.equal(scene.children.length,0);
console.log('Tyre smoke: rolling, lockup, burnout, lateral slip, unloaded wheel, actual physics, per-wheel origin, pool, expiry and cleanup passed.');
